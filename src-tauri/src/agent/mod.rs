//! agent 模块：会话与活跃 run 的管理入口（技术设计文档 §2.2/§5.1）。
//!
//! 名词解释：run 指一次模型任务的完整执行过程（从用户发送一条消息开始，
//! 到模型给出最终答复结束，中间可能经历多轮"模型输出 → 工具执行 → 再输出"）；
//! 会话（session）是用户与模型的持续对话上下文。
//!
//! 本模块是宿主命令层（Tauri 命令处理函数）的核心依赖，当前提供三件事：
//! - 同一会话同时只允许一个活跃 run，重复启动返回错误码 E_SESSION_RUNNING；
//! - cancel_run 命令把取消令牌置位后立即返回，真正的收尾由 run 任务自己
//!   完成（§5.3）；
//! - run 结束后把自己从注册表摘除。
//!
//! 后续能力（用户在模型回答过程中插话的 steer/followUp 队列、审批挂起与
//! 恢复的宿主侧、状态对账快照命令）会随对应的工单逐步加入。
//!
//! 对外类型统一从本模块重导出，调用方无需感知 run_manager 子模块的存在。

pub mod run_manager;

pub use run_manager::{RunHandle, RunManager, RunState, RunStatus};
